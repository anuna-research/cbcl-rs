#!/usr/bin/env python3
"""TEST-3807: capture literal renders from the pinned pre-SPEC implementation.

Uses only that revision's original source and input vectors in a temporary
checkout. The sole source edit prints raw render strings from its corpus test.
Run with --check to reproduce the committed fixture without overwriting it.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
import tempfile

REVISION = "3e222b072070eb1b4052fb5d448e899aa65967f3"
ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "test-vectors/state-pre-lvar-bytes.json"
PREFIX = "SPEC038_BASELINE "
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Compare regenerated bytes with the committed fixture")
options = parser.parse_args()


def git(*arguments):
    return subprocess.run(["git", *arguments], cwd=ROOT, check=True, capture_output=True).stdout


# Guard against silently moving the acceptance baseline after the new feature.
exists = subprocess.run(["git", "cat-file", "-e", f"{REVISION}:specs/SPEC-038-lvar-state-kernel.md"],
                        cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
if exists.returncode != 128:
    raise SystemExit("Expected a valid revision preceding SPEC-038")
expected_files = sorted(path.rsplit("/", 1)[1] for path in git(
    "ls-tree", "-r", "--name-only", REVISION, "test-vectors/state").decode().splitlines() if path.endswith(".json"))
with tempfile.TemporaryDirectory(prefix="cbcl-pre-lvar-render-") as temporary:
    directory = Path(temporary)
    archive = directory / "source.tar"
    archive.write_bytes(git("archive", REVISION))
    source = directory / "source"
    source.mkdir()
    subprocess.run(["tar", "-xf", str(archive), "-C", str(source)], check=True)
    test = source / "crates/cbcl-parser/tests/state_corpus.rs"
    text = test.read_text()
    anchor = "    let state = render_json(&fold(clause, d.causal_protocol.as_ref(), &accepted));"
    if text.count(anchor) != 1:
        raise SystemExit("Historical raw-render capture anchor is missing or ambiguous")
    capture = '\n    println!("SPEC038_BASELINE {}", serde_json::to_string(&json!({"file": path.file_name().unwrap().to_str().unwrap(), "vector": vector.clone(), "state_bytes": state.clone()})).unwrap());'
    test.write_text(text.replace(anchor, anchor + capture))
    environment = dict(os.environ, CARGO_INCREMENTAL="0", CARGO_PROFILE_TEST_DEBUG="0",
                       CARGO_TARGET_DIR=str(ROOT / "target/spec038-byte-baseline"))
    for variable in ["STATE_CORPUS_WRITE", "STATE_CORPUS_PRINT"]:
        environment.pop(variable, None)
    result = subprocess.run(["cargo", "test", "--offline", "-p", "cbcl-parser", "--test", "state_corpus", "--", "--nocapture"],
                            cwd=source, env=environment, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if result.returncode:
        print(result.stdout)
        raise SystemExit("Historical corpus must pass before its output can be a baseline")
    cases = [json.loads(line[len(PREFIX):]) for line in result.stdout.splitlines() if line.startswith(PREFIX)]
    cases.sort(key=lambda case: case["file"])
    if [case["file"] for case in cases] != expected_files:
        raise SystemExit("Historical capture must include each original vector exactly once")
    for case in cases:
        original = json.loads((source / "test-vectors/state" / case["file"]).read_text())
        if case["vector"] != original or not isinstance(case["state_bytes"], str):
            raise SystemExit("Historical capture changed an original vector or omitted raw bytes")
    fixture = {"format": 1, "baseline_revision": REVISION,
               "corpus_version": (source / "test-vectors/state/VERSION").read_text().strip(), "cases": cases}
    rendered = json.dumps(fixture, indent=2, ensure_ascii=False) + "\n"
    if options.check:
        if DESTINATION.read_text() != rendered:
            raise SystemExit("Committed raw-render fixture differs from the historical implementation")
        print(f"PASS: reproduced {len(cases)} original raw-render baselines from {REVISION}")
    else:
        DESTINATION.write_text(rendered)
        print(f"Captured {len(cases)} original raw-render baselines from {REVISION}")
