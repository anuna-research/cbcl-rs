export type FieldType = 'string' | 'hlc' | 'integer' | 'number' | 'float' | 'decimal' | 'nonnegative' | 'bool' | 'symbol' | 'keyword' | 'list';
/** A built-in name, local type name, or CBCL contract expression; validated by the shared core. */
export interface ShapeField {
  type?: string; optional?: boolean; default?: string;
  children?: Record<string, string | ShapeField> | string[];
}
export type FieldSpec = FieldType | (string & {}) | { enumOf: string } | ShapeField;
export type RuleOp = 'lwwRegister' | 'lwwMap' | 'lwwPerSigner' | 'multiValueRegister' | 'multiValueMap' | 'initial' | 'exists' | 'count' | 'progress' | 'events' | 'setUnion'
  | 'values' | 'valuesPerKey' | 'observedSet' | 'counter' | 'histogram' | 'sum';

export interface VerbSpec { after: string[]; fields: Record<string, FieldSpec>; from?: string; to?: string[] }

/** The wire contract record (SPEC-087 CON-001). */
export interface Contract {
  version: 3;
  kind: 'contract';
  name: string;
  author?: string;
  requirements?: { maxDepth?: number; maxExpansionSize?: number; verificationTime?: number };
  bounds?: { maxString?: number; maxList?: number; maxNumber?: number; maxFields?: number };
  /** Local named flat contracts, expressed as CBCL type-expression text. */
  types?: Record<string, string>;
  roles?: Record<string, 'singleton' | 'indexed'>;
  verbs: Record<string, VerbSpec>;
  state: Record<string, Rule>;
  stateEntries?: string[];
}

/** Native state clause syntax as nested arrays. Strings denote symbols or :keywords;
 * use { str: 'text' } for quoted strings and ordinary numbers for integer atoms. */
export type StateForm = ExactScalar | bigint | { str: string } | StateForm[];
function statePart(part: StateForm): string {
  if (Array.isArray(part)) return '(' + part.map(statePart).join(' ') + ')';
  if (typeof part === 'object' && 'str' in part) return literal(part.str);
  if (typeof part !== 'string') return literal(part);
  return part.startsWith(':') ? literal({ keyword: part.slice(1) }) : literal({ symbol: part });
}
export function stateEntry(head: string, ...parts: StateForm[]): string {
  return statePart([head, ...parts]);
}

/** Define an optional shape field. The default is encoded as a CBCL literal. */
export function optional(type: string, defaultValue?: Plain): ShapeField {
  return defaultValue === undefined ? { type, optional: true } : { type, optional: true, default: literal(defaultValue) };
}

